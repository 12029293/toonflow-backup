#!/usr/bin/env python3
"""Collect the non-sensitive, human-authored assets from the Toonflow data dir.

What gets backed up and why:

  skills/        prompt/knowledge base authored here - real text, worth keeping
  providers/     custom provider .ts sources (yuxibox, yingce) - real code
  workspaces/*.json   canvas documents - the actual node graphs
  ext/*.json     extension registry metadata
  settings.json  sanitised config (api keys stripped)

What is deliberately excluded:

  workspaces/assets/**   generated media (images/video/audio), ~99 MB of binaries
  workspaces/.agent/**   agent session transcripts, 48 MB, contains chat logs
  ffmpeg/                153 MB of downloadable binaries
  nodes/ tools/ ext/*.umd.js   build output, regenerated by `bun run build:server`
  *.umd.js everywhere    compiled bundles, not source
"""

import json
import os
import re
import shutil
import sys

DATA = "/data/home/toonflow/data"
OUT = "/data/home/toonflow/code-export"

# Matches values that must never leave the machine.
SECRET_RE = re.compile(
    r"(sk-[A-Za-z0-9_\-]{16,}|ibk_[a-z0-9]{16,}|ghp_[A-Za-z0-9]{20,}"
    r"|Bearer\s+[A-Za-z0-9._\-]{20,})"
)


def log(msg):
    print(msg, flush=True)


def scrub_secrets(text):
    """Replace credential-looking substrings so an accidental leak cannot ship."""
    return SECRET_RE.sub(lambda m: m.group(1)[:4] + "***REDACTED***", text)


def copy_tree(src, dst, exts=None):
    """Copy text files, skipping binaries and scrubbing secrets in place."""
    count = 0
    for root, dirs, files in os.walk(src):
        dirs[:] = [d for d in dirs if d not in ("node_modules", ".git", "__pycache__")]
        for name in files:
            if exts and os.path.splitext(name)[1].lower() not in exts:
                continue
            src_path = os.path.join(root, name)
            rel = os.path.relpath(src_path, src)
            dst_path = os.path.join(dst, rel)
            os.makedirs(os.path.dirname(dst_path), exist_ok=True)
            try:
                with open(src_path, "r", encoding="utf-8") as handle:
                    content = handle.read()
            except (UnicodeDecodeError, OSError):
                continue  # binary or unreadable; skip rather than ship junk
            with open(dst_path, "w", encoding="utf-8", newline="\n") as handle:
                handle.write(scrub_secrets(content))
            count += 1
    return count


def sanitise_settings(src, dst):
    """Keep harmless prefs, drop anything key/token shaped."""
    with open(src, "r", encoding="utf-8") as handle:
        data = json.load(handle)

    removed = []

    def walk(node):
        if isinstance(node, dict):
            for key in list(node.keys()):
                lowered = key.lower()
                if any(token in lowered for token in ("key", "token", "secret", "password", "cookie")):
                    node.pop(key)
                    removed.append(key)
                else:
                    walk(node[key])
        elif isinstance(node, list):
            for item in node:
                walk(item)

    walk(data)
    with open(dst, "w", encoding="utf-8", newline="\n") as handle:
        json.dump(data, handle, ensure_ascii=False, indent=2)
    return removed


def main():
    if os.path.isdir(OUT):
        shutil.rmtree(OUT)
    os.makedirs(OUT, exist_ok=True)

    summary = []

    # --- skills: prompt knowledge base ---
    skills_src = os.path.join(DATA, "skills")
    if os.path.isdir(skills_src):
        n = copy_tree(skills_src, os.path.join(OUT, "skills"), {".md", ".txt", ".json"})
        summary.append(("skills/", n, "prompt knowledge base"))

    # --- providers: custom provider sources ---
    prov_src = os.path.join(DATA, "providers")
    if os.path.isdir(prov_src):
        n = copy_tree(prov_src, os.path.join(OUT, "providers"), {".ts", ".js", ".json"})
        summary.append(("providers/", n, "custom provider sources"))

    # --- canvas documents ---
    ws_dir = os.path.join(DATA, "workspaces")
    canvas_out = os.path.join(OUT, "canvases")
    os.makedirs(canvas_out, exist_ok=True)
    canvas_count = 0
    if os.path.isdir(ws_dir):
        for name in sorted(os.listdir(ws_dir)):
            if not name.lower().endswith(".json"):
                continue
            src_path = os.path.join(ws_dir, name)
            if not os.path.isfile(src_path):
                continue
            with open(src_path, "r", encoding="utf-8") as handle:
                content = handle.read()
            with open(os.path.join(canvas_out, name), "w", encoding="utf-8", newline="\n") as handle:
                handle.write(scrub_secrets(content))
            canvas_count += 1
    summary.append(("canvases/", canvas_count, "canvas node graphs"))

    # --- extension registry metadata (bundled.json only, not the .umd.js builds) ---
    ext_src = os.path.join(DATA, "ext")
    if os.path.isdir(ext_src):
        ext_out = os.path.join(OUT, "ext")
        os.makedirs(ext_out, exist_ok=True)
        n = 0
        for name in os.listdir(ext_src):
            if name.endswith(".json"):
                with open(os.path.join(ext_src, name), "r", encoding="utf-8") as handle:
                    content = handle.read()
                with open(os.path.join(ext_out, name), "w", encoding="utf-8", newline="\n") as handle:
                    handle.write(scrub_secrets(content))
                n += 1
        summary.append(("ext/", n, "extension registry metadata"))

    # --- settings, sanitised ---
    settings_src = os.path.join(DATA, "settings.json")
    if os.path.isfile(settings_src):
        removed = sanitise_settings(settings_src, os.path.join(OUT, "settings.json"))
        summary.append(("settings.json", 1, "sanitised (removed: %s)" % (", ".join(removed) or "none")))

    # --- report ---
    total_files = 0
    total_bytes = 0
    for root, _dirs, files in os.walk(OUT):
        for name in files:
            total_files += 1
            total_bytes += os.path.getsize(os.path.join(root, name))

    log("=== collected ===")
    for name, count, note in summary:
        log("  %-16s %3d files  %s" % (name, count, note))
    log("  ---")
    log("  total %d files, %.1f KB" % (total_files, total_bytes / 1024))

    # Final safety pass: fail loudly if anything key-shaped survived.
    hits = []
    for root, _dirs, files in os.walk(OUT):
        for name in files:
            path = os.path.join(root, name)
            with open(path, "r", encoding="utf-8", errors="ignore") as handle:
                text = handle.read()
            for match in SECRET_RE.finditer(text):
                hits.append((os.path.relpath(path, OUT), match.group(1)[:12]))

    if hits:
        log("")
        log("!!! %d credential-like strings remain:" % len(hits))
        for path, sample in hits[:20]:
            log("   %s : %s..." % (path, sample))
        return 1

    log("")
    log("no credentials detected in the export")
    return 0


if __name__ == "__main__":
    sys.exit(main())
